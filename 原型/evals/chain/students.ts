// 链路评测的模拟学生：每类一个人设 + 真实知识状态。学生只看得到界面上的文字（驱动按界面规则转好再给它），
// 看不到系统提示、诊断记录、工具调用与程序事实。知识状态同时交给判分器，用来分辨“系统判错了”还是“学生没演对”。
// 教材是 样例/ 里的力学入门（位置 → 位移 → 平均速度 → 瞬时速度 → 加速度 → 匀加速 → 力、惯性、质量 → 牛顿第二定律）。

/** 守卫对这类学生的期望：判合上 / 不判合上 / 只记录。 */
export type GuardExpectation = 'close' | 'not_close' | 'observe';

export interface Student {
  /** 命令行里用的短名。 */
  id: string;
  name: string;
  /** 这个人是谁、为什么学、怎么说话、怎么学。 */
  persona: string;
  /** 真实知识状态（守卫看不到；学生据此答题，判分器据此分辨归因）。 */
  knowledge: string;
  /** 守卫期望。 */
  guard: GuardExpectation;
  /** 这类学生学习对话怎么收尾才算按人设走（给判分器看）。 */
  expectedEnding: string;
  /** 判分器看教学时的重点（诊断准不准、误解有没有被处理……）。 */
  teachingFocus: string;
  /** 额外观察项（跑题、放弃），给判分器的观察提示；没有就不跑。 */
  observeFocus?: string;
  /** 学习对话里第 2 句起、模型答到一半时插的一句话。 */
  interjection: string;
  /** 学习对话里学生最多说几轮（到了驱动代点“先到这里”）。 */
  maxLoopTurns: number;
  /** 畅谈里最多说几轮。 */
  maxTalkTurns: number;
}

